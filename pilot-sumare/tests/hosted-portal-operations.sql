begin;
create temporary table portal_fixture on commit drop as select gen_random_uuid() as candidate,gen_random_uuid() as company,gen_random_uuid() as school,gen_random_uuid() as outsider,gen_random_uuid() as owner,gen_random_uuid() as cohort,gen_random_uuid() as job,gen_random_uuid() as course,gen_random_uuid() as application;
grant select on portal_fixture to authenticated,service_role,anon;
insert into auth.users(id,email,email_confirmed_at,raw_user_meta_data)
select id,'portal-rls-'||id::text||'@example.invalid',now(),'{"display_name":"Fixture transacional","role":"pilot_owner"}'::jsonb from portal_fixture f cross join lateral unnest(array[f.candidate,f.company,f.school,f.outsider,f.owner]) id;
insert into public.pilot_cohorts(id,slug,school_name,city,starts_at) select cohort,'portal-fixture-'||cohort::text,'Teste transacional','Campinas',now() from portal_fixture;
insert into public.pilot_memberships(cohort_id,user_id,role,status) select f.cohort,v.id,v.role,'active' from portal_fixture f cross join lateral(values(f.candidate,'learner'),(f.company,'recruiter'),(f.school,'school_staff'),(f.outsider,'recruiter'),(f.owner,'pilot_owner')) v(id,role);
insert into public.pilot_profiles(user_id,display_name,skills,city,state_code) select id,'Pessoa Fictícia','Modelagem 3D','Campinas','SP' from portal_fixture f cross join lateral unnest(array[f.candidate,f.company,f.school,f.outsider,f.owner]) id;
select set_config('request.jwt.claim.sub',company::text,true) from portal_fixture;
set local role authenticated;
insert into public.portal_listings(cohort_id,publisher_id,kind,title,organization,description,postal_code,city,state_code,modality,job_type) select cohort,company,'job','Desenhista de teste','Empresa Fictícia','Descrição fictícia para verificação transacional.','13000000','Campinas','SP','Presencial','CLT' from portal_fixture;
reset role;
update portal_fixture set job=(select id from public.portal_listings where cohort_id=portal_fixture.cohort and kind='job');
select set_config('request.jwt.claim.sub',school::text,true) from portal_fixture;
set local role authenticated;
do $$begin
 begin insert into public.portal_listings(cohort_id,publisher_id,kind,title,organization,description,postal_code,city,state_code,modality,job_type) select cohort,school,'job','Vaga indevida','Fixture','Não pode criar vaga por perfil escolar.','13000000','Campinas','SP','Presencial','CLT' from portal_fixture;raise exception 'School job publication allowed';exception when insufficient_privilege then null;end;
 if exists(select 1 from public.pilot_profiles p join portal_fixture f on p.user_id=f.school) then raise exception 'School candidate profile exposed';end if;
end$$;
insert into public.portal_listings(cohort_id,publisher_id,kind,title,organization,description,postal_code,city,state_code,modality) select cohort,school,'course','Curso de teste','Escola Fictícia','Descrição fictícia para verificação transacional.','13000000','Campinas','SP','Online' from portal_fixture;
reset role;
update portal_fixture set course=(select id from public.portal_listings where cohort_id=portal_fixture.cohort and kind='course');
select set_config('request.jwt.claim.sub',candidate::text,true) from portal_fixture;
set local role authenticated;
insert into public.portal_applications(listing_id,cohort_id,candidate_id,message) select job,cohort,candidate,'Candidatura transacional' from portal_fixture;
insert into public.portal_applications(listing_id,cohort_id,candidate_id,message) select course,cohort,candidate,'Interesse transacional' from portal_fixture;
do $$begin
 if exists(select 1 from public.portal_applications a join portal_fixture f on a.listing_id=f.course where a.resume_snapshot ? 'skills') then raise exception 'Course received full resume';end if;
 begin update public.portal_applications set status='accepted';raise exception 'Candidate changed employer status';exception when insufficient_privilege then null;end;
end$$;
reset role;
update portal_fixture set application=(select id from public.portal_applications where listing_id=portal_fixture.job);
select set_config('request.jwt.claim.sub',outsider::text,true) from portal_fixture;
set local role authenticated;
do $$begin
 if exists(select 1 from public.portal_applications a join portal_fixture f on a.cohort_id=f.cohort) then raise exception 'Other company application leak';end if;
 begin perform public.portal_respond_application(application,'accepted','Resposta indevida') from portal_fixture;raise exception 'Other company response allowed';exception when raise_exception then if SQLERRM<>'Acesso negado' then raise;end if;end;
end$$;
reset role;
select set_config('request.jwt.claim.sub',company::text,true) from portal_fixture;
set local role authenticated;
select public.portal_respond_application(application,'interview','Convidamos para entrevista de teste') from portal_fixture;
reset role;
select set_config('request.jwt.claim.sub',candidate::text,true) from portal_fixture;
set local role authenticated;
do $$begin
 if not exists(select 1 from public.portal_notifications n join portal_fixture f on n.user_id=f.candidate and n.listing_id=f.job) then raise exception 'Reply notification missing';end if;
end$$;
select public.portal_withdraw_application(application) from portal_fixture;
reset role;
set local role service_role;
select public.portal_owner_metrics(owner,cohort,now()-interval '1 day',now()+interval '1 minute','day') from portal_fixture;
select public.portal_broadcast(owner,cohort,'learner',array['SP'],'Campinas','Teste de aviso','Mensagem transacional',false) from portal_fixture;
reset role;
update public.pilot_memberships set status='suspended' where user_id=(select company from portal_fixture);
select set_config('request.jwt.claim.sub',company::text,true) from portal_fixture;
set local role authenticated;
do $$begin if exists(select 1 from public.portal_applications a join portal_fixture f on a.cohort_id=f.cohort) then raise exception 'Suspended company read applications';end if;end$$;
reset role;
set local role anon;
do $$begin if not exists(select 1 from public.portal_listings l join portal_fixture f on l.id=f.job) then raise exception 'Public listing missing';end if;begin perform publisher_id from public.portal_listings;raise exception 'Anonymous publisher identifier exposed';exception when insufficient_privilege then null;end;end$$;
reset role;
select set_config('request.jwt.claim.sub',candidate::text,true) from portal_fixture;
set local role authenticated;
insert into public.portal_candidate_cards(id,user_id,cohort_id,name,headline,visible) select candidate,candidate,cohort,'Pessoa Fictícia','Desenhista 3D',false from portal_fixture;
reset role;
set local role anon;
do $$begin if exists(select 1 from public.portal_candidate_cards where id=(select candidate from portal_fixture)) then raise exception 'Unconsented candidate exposed';end if;end$$;
reset role;
set local role authenticated;
update public.portal_candidate_cards set visible=true where user_id=(select candidate from portal_fixture);
reset role;
set local role anon;
do $$begin if not exists(select 1 from public.portal_candidate_cards where id=(select candidate from portal_fixture)) then raise exception 'Consented public candidate missing';end if;begin perform user_id from public.portal_candidate_cards;raise exception 'Private candidate identifier exposed';exception when insufficient_privilege then null;end;end$$;
reset role;
rollback;
select jsonb_build_object('hosted_operations_test','passed','fixture_users_remaining',(select count(*) from auth.users where email like 'portal-rls-%@example.invalid'),'fixture_cohorts_remaining',(select count(*) from public.pilot_cohorts where slug like 'portal-fixture-%')) as verification;
